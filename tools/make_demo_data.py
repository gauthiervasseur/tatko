#!/usr/bin/env python3
"""Generate the fictional 'Pixel Mart' retro-electronics sales dataset used by DEMO.

Deterministic (fixed seed), so the demo looks the same on every build.
Writes app/samples/pixel-mart-sales.csv and app/samples/demo-data.js.
"""
import csv
import io
import json
import math
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "samples"
random.seed(1984)

COUNTRIES = {
    "Europe": ["France", "Germany", "Ukraine", "Poland", "Spain"],
    "Americas": ["USA", "Canada", "Brazil", "Mexico"],
    "Asia-Pacific": ["Japan", "South Korea", "Australia", "Singapore"],
}
REGION_WEIGHT = {"Europe": 0.42, "Americas": 0.36, "Asia-Pacific": 0.22}
CHANNELS = [("Online", 0.5), ("Retail Store", 0.35), ("Arcade Hall", 0.15)]
# category -> [(product, unit price, unit cost)]
CATALOG = {
    "Consoles": [("Nova 8 Console", 189, 121), ("Nova 8 Mini", 99, 58), ("Pocket Pixel", 79, 44)],
    "Cartridges": [("Starfall Run", 39, 12), ("Cave Knight", 35, 11), ("Turbo Grid", 29, 9), ("Moon Miner", 32, 10)],
    "Accessories": [("Joystick Pro", 49, 21), ("Twin Pad", 25, 9), ("Light Blaster", 59, 27), ("Memory Card 64K", 15, 4)],
    "Cabinets": [("Upright Cabinet", 2400, 1650), ("Cocktail Table", 1800, 1210)],
    "Merch": [("Pixel Tee", 22, 7), ("Coin Mug", 14, 4), ("Sprite Poster", 12, 3)],
}
CAT_WEIGHT = {"Consoles": 0.17, "Cartridges": 0.34, "Accessories": 0.27, "Cabinets": 0.04, "Merch": 0.18}


def pick(weighted):
    r = random.random() * sum(w for _, w in weighted)
    for item, w in weighted:
        r -= w
        if r <= 0:
            return item
    return weighted[-1][0]


def main():
    start, end = date(2023, 1, 1), date(2025, 12, 31)
    days = (end - start).days + 1
    rows = []
    oid = 100000
    for _ in range(4200):
        # seasonality: December peak, summer bump, growth over time
        while True:
            d = start + timedelta(days=random.randrange(days))
            season = 1 + 0.9 * math.exp(-((d.month - 12) ** 2) / 1.5) + 0.25 * math.exp(-((d.month - 7) ** 2) / 2)
            growth = 1 + 0.35 * (d - start).days / days
            if random.random() < season * growth / 2.6:
                break
        region = pick(list(REGION_WEIGHT.items()))
        country = random.choice(COUNTRIES[region])
        channel = pick(CHANNELS)
        category = pick(list(CAT_WEIGHT.items()))
        if category == "Cabinets" and channel == "Online" and random.random() < 0.6:
            channel = "Arcade Hall"
        product, price, cost = random.choice(CATALOG[category])
        units = 1 if category == "Cabinets" else max(1, int(random.expovariate(1 / 3)) + 1)
        discount = random.choice([0, 0, 0, 0.05, 0.1, 0.15, 0.2]) if channel != "Arcade Hall" else 0
        revenue = round(units * price * (1 - discount), 2)
        cogs = round(units * cost, 2)
        rating = None if random.random() < 0.18 else min(5, max(1, round(random.gauss(4.1 - discount * 3, 0.7))))
        oid += random.randint(1, 3)
        rows.append({
            "Order ID": f"PM-{oid}",
            "Order Date": d.isoformat(),
            "Region": region,
            "Country": country,
            "Channel": channel,
            "Category": category,
            "Product": product,
            "Units": units,
            "Unit Price": price,
            "Discount": discount,
            "Revenue": revenue,
            "Cost": cogs,
            "Profit": round(revenue - cogs, 2),
            "Rating": "" if rating is None else rating,
        })
    rows.sort(key=lambda r: (r["Order Date"], r["Order ID"]))

    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    text = buf.getvalue()

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "pixel-mart-sales.csv").write_text(text, encoding="utf-8")
    (OUT / "demo-data.js").write_text(
        "/* Generated by tools/make_demo_data.py - fictional data for the DEMO button. */\n"
        "window.TATKO_DEMO_CSV = " + json.dumps(text) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(rows)} demo rows -> {OUT}")


if __name__ == "__main__":
    main()
